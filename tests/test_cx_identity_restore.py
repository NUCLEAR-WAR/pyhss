def test_explicit_pending_cancellation_keeps_credentials_and_rejects_registered_state(lab):
    d,_=lab;svc,ims,old=old_generated_profile(d);ident=ims['ims_subscriber_id'];private=old['provisioning']['private_identity']
    public=next(x['identity'] for x in old['public_identities'] if x['identity'].startswith('sip:+'))
    with svc.repo.engine.connect() as c:before=list(c.execute(select(svc.repo.auc)))
    mar(d,private,public)
    with pytest.raises(ValueError,match='De-register'):tool().restore(svc.repo,[ident],apply=True)
    tool().restore(svc.repo,[ident],apply=True,clear_authentication_pending=True)
    assert snapshot(d,private,public[:-len(';user=phone')])['scscf'] is None
    with svc.repo.engine.connect() as c:assert list(c.execute(select(svc.repo.auc)))==before
    svc,ims,old=old_generated_profile(d);ident=ims['ims_subscriber_id'];private=old['provisioning']['private_identity']
    public=next(x['identity'] for x in old['public_identities'] if x['identity'].startswith('sip:+'))
    mar(d,private,public);sar(d,1,private,public)
    with pytest.raises(ValueError,match='Cannot clear'):tool().restore(svc.repo,[ident],apply=True,clear_authentication_pending=True)

def test_restore_conflicting_uri_policies_requires_operator_review(lab):
    d,_=lab;_,_,old=old_generated_profile(d)
    marked=next(x for x in old['public_identities'] if x['identity'].startswith('sip:+'))
    bare=deepcopy(marked);bare['identity']=bare['identity'][:-len(';user=phone')];bare['barred']=not marked['barred']
    old['public_identities'].append(bare)
    with pytest.raises(ValueError,match='merge existing identities'):tool().restored_definition(old)

def test_cli_default_is_read_only_without_schema_initialization(lab,monkeypatch,capsys):
    import database,sys
    d,_=lab;svc,ims,_=old_generated_profile(d);repo=svc.repo;ident=ims['ims_subscriber_id'];before=rows(repo,ident)
    module=tool();statements=[]
    monkeypatch.setattr(database,'database_connection_settings',lambda cfg:(repo.engine.url,{}))
    monkeypatch.setattr(module,'create_engine',lambda *a,**kw:repo.engine)
    monkeypatch.setattr(sys,'argv',['restore_cx_client_identities.py','--ims-subscriber-id',str(ident)])
    def capture(conn,cursor,statement,parameters,context,executemany):statements.append(statement)
    event.listen(repo.engine,'before_cursor_execute',capture)
    try:module.main()
    finally:event.remove(repo.engine,'before_cursor_execute',capture)
    assert '"mode": "dry-run"' in capsys.readouterr().out
    assert all(not sql.lstrip().upper().startswith(('CREATE','ALTER','INSERT','UPDATE','DELETE','DROP')) for sql in statements)
    assert rows(repo,ident)==before
